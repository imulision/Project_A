import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const url = 'file://' + path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../web/index.html') + '?fixed&manual';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 })).newPage();
page.on('pageerror', (e) => console.log('ERR', String(e)));
await page.goto(url);
await page.waitForFunction(() => window.__ashport && window.__ashport.map(), null, { timeout: 120000 });
await page.click('[data-act=start]');
await page.evaluate(() => { for (let i = 0; i < 60; i++) { window.__ashport.beat(); document.querySelectorAll('#veil.on [data-act=close]').forEach(b => b.click()); } window.__ashport.home(); });
await page.waitForFunction(() => !window.__ashport.map().stats().moving, null, { timeout: 60000 });
await page.waitForTimeout(3000);
console.log(await page.evaluate(() => ({ d: document.getElementById('dirtyd').textContent, c: document.getElementById('cleand').textContent, tags: [...document.querySelectorAll('.lab.tag')].map(e => e.className + ':' + e.textContent) })));
await page.screenshot({ path: process.argv[2] + '/money.png' });
const f = await page.locator('.lab.capo').first().boundingBox();
await page.touchscreen.tap(f.x + f.width / 2, f.y + f.height / 2); await page.waitForTimeout(700);
await page.screenshot({ path: process.argv[2] + '/capo.png' });
await browser.close();
